-- Migration 003 — Case file uploads (Supabase Storage) with per-file client visibility
-- Run on an EXISTING database (safe to run more than once). Adds one new table only.
-- The private storage bucket (default name: case-documents) is created automatically
-- by the app on the first upload, or create it yourself in Storage (keep it PRIVATE).
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.case_files (
    file_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id        BIGINT NOT NULL REFERENCES public.cases(case_id) ON UPDATE CASCADE ON DELETE CASCADE,
    file_name      VARCHAR(150) NOT NULL,
    storage_path   TEXT NOT NULL UNIQUE,
    content_type   VARCHAR(100) NOT NULL,
    size_bytes     BIGINT NOT NULL CHECK (size_bytes > 0),
    client_visible BOOLEAN NOT NULL DEFAULT FALSE,
    created_at     TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_case_files_case ON public.case_files(case_id);

ALTER TABLE public.case_files ENABLE ROW LEVEL SECURITY;
